// ---------------------------------------------------------------------------
// Write the voiceover as one continuous block, with the pauses baked in.
//
// Seventeen separate takes give the tightest sync, but they are seventeen
// pastes and seventeen files to place. This emits one script instead: every
// line in order, separated by <break> tags sized so that each line lands on its
// cue in media/tracer-silent.mp4 when read at the pace the script assumes.
//
// The gaps come from the same cue sheet the assembler writes, so the script and
// the picture cannot drift. Break tags cap at 3 seconds each, so longer gaps
// are chained.
//
//   node scripts/make-vo-script.mjs          # writes docs/VOICEOVER-PASTE.md
//   node scripts/make-vo-script.mjs --wpm 175
// ---------------------------------------------------------------------------

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = path.resolve(fileURLToPath(new URL('..', import.meta.url)));
const SCRIPT = path.join(REPO, 'docs/VOICEOVER.md');
const CUES = path.join(REPO, 'media/vo-cues.json');
const OUT = path.join(REPO, 'docs/VOICEOVER-PASTE.md');

const argv = process.argv.slice(2);
const i = argv.indexOf('--wpm');
const WPM = i === -1 ? 160 : Number(argv[i + 1]);

/** The numbered lines, in order, out of the markdown. */
function parseScript() {
  const md = readFileSync(SCRIPT, 'utf8');
  const lines = [];
  const re = /^\*\*(\d{2})\*\*(.*)$/gm;
  let m;
  while ((m = re.exec(md))) {
    const rest = md.slice(m.index + m[0].length);
    const stop = rest.search(/^\*\*\d{2}\*\*|^## /m);
    const body = stop === -1 ? rest : rest.slice(0, stop);
    const text = body
      .split(/\r?\n/)
      .filter((l) => l.trim().startsWith('>'))
      .map((l) => l.replace(/^\s*>\s?/, '').trim())
      .join(' ')
      .replace(/\s+/g, ' ')
      .trim();
    if (text) lines.push({ id: m[1], text });
  }
  return lines.sort((a, b) => a.id.localeCompare(b.id));
}

/**
 * One break tag, for the pause between two lines.
 *
 * A tag caps at 3 seconds, and the docs are explicit that stacking them makes
 * the model speed up or add artefacts. So a longer gap is not chained: the tag
 * is capped at 3s and the rest of the silence is left to the edit, where a gap
 * between two clips costs nothing and carries no risk of destabilising a read.
 *
 * Returns the tag and the seconds it does not cover.
 */
function breakFor(secs) {
  const want = Math.round(secs * 10) / 10;
  // Under a quarter second is a breath the reader takes anyway, and a tag that
  // short reads as a stutter rather than a pause.
  if (want < 0.25) return { tag: '', uncovered: want };
  const tagged = Math.min(3, want);
  return {
    tag: `<break time="${tagged.toFixed(1)}s" />`,
    uncovered: Math.round((want - tagged) * 10) / 10,
  };
}

const lines = parseScript();
const cues = JSON.parse(readFileSync(CUES, 'utf8'));

// Walk the cue sheet, tracking where the read has got to. The gap before a line
// is the distance between its cue and the end of the line before it.
let cursor = 0;
let spoken = 0;
let padding = 0;
const parts = [];
const table = [];

// A gap longer than one tag can carry ends the block. Everything after it is a
// separate generation, placed in the edit at the timecode given. Two or three
// files is a far smaller cost than a chain of stacked tags destabilising the
// whole read.
const blocks = [[]];
const starts = [0];

for (const l of lines) {
  const cue = cues.lines[l.id];
  if (!cue) throw new Error('no cue for line ' + l.id);
  const gap = cue.at - cursor;
  const { tag, uncovered } = breakFor(gap);

  if (uncovered > 0.4) {
    // Too long to tag. Start a new block at this line's cue.
    blocks.push([]);
    starts.push(cue.at);
  } else if (tag) {
    blocks[blocks.length - 1].push(tag);
    padding += gap;
  }

  const secs = l.text.split(/\s+/).length / WPM * 60;
  blocks[blocks.length - 1].push(l.text);
  parts.push(l.text);
  table.push({
    id: l.id, at: cue.at, gap: Math.max(0, gap), secs, clip: cue.clip,
    block: blocks.length,
  });
  cursor = cue.at + secs;
  spoken += secs;
}

const hhmmss = (s) => `${Math.floor(s / 60)}:${(s - Math.floor(s / 60) * 60).toFixed(1).padStart(4, '0')}`;

const blockDoc = blocks.map((b, i) => {
  const lastAt = table.filter((t) => t.block === i + 1).pop();
  const ends = lastAt ? lastAt.at + lastAt.secs : starts[i];
  const head = `### Part ${i + 1}, place at **${hhmmss(starts[i])}**`;
  const runs = `Runs about ${(ends - starts[i]).toFixed(0)}s.`;
  const fence = ['```', b.join('\n\n'), '```'].join('\n');
  return [head, runs, fence].join('\n\n');
}).join('\n\n');

const doc = `# Voiceover, ready to paste

Generated by \`node scripts/make-vo-script.mjs\`. Do not edit this file: edit
\`docs/VOICEOVER.md\` and run that again, or the words and the picture drift.

${blocks.length === 1
  ? 'One generation. Paste the whole block below.'
  : `**${blocks.length} generations**, one per part below. They are separate because the
silences between them are longer than a single \`<break>\` tag can carry, and
stacking tags to cover a long gap makes the model speed up or add artefacts.
Place each part at the timecode on its heading; the silence between parts is
just empty timeline.`}

- Written for **${WPM} words per minute**. ${lines.length} lines, ${spoken.toFixed(0)}s of speech.
- \`<break>\` needs **Eleven Multilingual v2**. v3 dropped break tags, and on v3
  this would read straight through with no pauses at all.
- Paste the text inside the code fence only. Not the heading, not the fence.
- If your take comes out much longer or shorter than expected, send it to me
  rather than re-reading. Resizing the picture to your voice is a rebuild on my
  side; re-recording is work on yours.

---

${blockDoc}

---

## Where each line lands

Timecodes are into \`media/tracer-silent.mp4\` (${hhmmss(cues.total)}).

| line | part | at | pause before | runs | over |
|---|---|---|---|---|---|
${table.map((t) => `| ${t.id} | ${t.block} | ${hhmmss(t.at)} | ${t.gap.toFixed(1)}s | ${t.secs.toFixed(1)}s | \`${t.clip}\` |`).join('\n')}

## If it does not fit

The pauses assume ${WPM} wpm. Regenerate for your actual pace with, for example,
\`node scripts/make-vo-script.mjs --wpm 175\`, which resizes every tag and
re-splits the parts without touching a word.
`;

writeFileSync(OUT, doc);
console.log(`${lines.length} lines in ${blocks.length} part(s), ${spoken.toFixed(1)}s speech`);
console.log(`picture is ${cues.total}s, script lands at ${(cursor).toFixed(1)}s`);
console.log(`-> docs/VOICEOVER-PASTE.md`);
