// ---------------------------------------------------------------------------
// Generate the voiceover from docs/VOICEOVER.md, one file per line.
//
// The script is parsed out of the markdown rather than duplicated here, so
// there is one copy of the words. Editing docs/VOICEOVER.md and re-running this
// is the whole workflow; a line whose text has not changed is not re-generated
// and not re-billed.
//
// Needs ELEVENLABS_API_KEY in the environment or in .env.
//
//   node scripts/make-voiceover.mjs                 # generate what is missing
//   node scripts/make-voiceover.mjs --force         # regenerate everything
//   node scripts/make-voiceover.mjs --line 08       # just that one
//   node scripts/make-voiceover.mjs --voices        # list voices, generate nothing
//   node scripts/make-voiceover.mjs --voice <id>    # use a specific voice
// ---------------------------------------------------------------------------

import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';

const REPO = path.resolve(fileURLToPath(new URL('..', import.meta.url)));
const SCRIPT = path.join(REPO, 'docs/VOICEOVER.md');
const OUT = path.join(REPO, 'media/vo');
const API = 'https://api.elevenlabs.io/v1';
const FFMPEG = process.env.FFMPEG_PATH || 'ffmpeg';
const FFPROBE = process.env.FFPROBE_PATH || 'ffprobe';

// --- key ---------------------------------------------------------------------

function apiKey() {
  if (process.env.ELEVENLABS_API_KEY) return process.env.ELEVENLABS_API_KEY.trim();
  const envFile = path.join(REPO, '.env');
  if (existsSync(envFile)) {
    const m = readFileSync(envFile, 'utf8').match(/^\s*ELEVENLABS_API_KEY\s*=\s*(.+)$/m);
    if (m) return m[1].trim().replace(/^["']|["']$/g, '');
  }
  console.error('No ELEVENLABS_API_KEY. Put it in .env as:\n\n  ELEVENLABS_API_KEY=...\n');
  process.exit(1);
}

// --- settings ----------------------------------------------------------------

// Daniel, "Steady Broadcaster". Chosen on measured pace rather than on the
// label: reading line 08, Daniel runs 144 wpm against 169 to 194 for Adam,
// Brian, George and Eric. That is documentary pace; the others are closer to an
// advertising read, and this material cannot survive being sold.
//
// Auditions for all five are regenerated by scripts/audition-voices.mjs.
const DEFAULT_VOICE = process.env.ELEVENLABS_VOICE_ID || 'onwK4e9ZLuTAKqWW03F9';

const SETTINGS = {
  // Low enough to keep inflection across a three minute read, high enough not
  // to wander between paragraphs generated in separate requests.
  stability: 0.5,
  similarity_boost: 0.8,
  // Anything above zero pushes this towards an advertising read, which is the
  // one tone this material cannot survive.
  style: 0,
  use_speaker_boost: true,
};
// Multilingual v2 rather than v3: it honours <break time="x.xs" /> for the
// timed pauses the script needs, which v3 dropped in favour of audio tags.
const MODEL = 'eleven_multilingual_v2';
// 128kbps: 192 requires a paid tier, and the difference is inaudible for a
// single voice sitting under music.
const FORMAT = 'mp3_44100_128';

// --- parse the script --------------------------------------------------------

/**
 * Pull the numbered lines out of the markdown.
 *
 * A line is a `**NN**` marker followed by one or more blockquote paragraphs.
 * Everything else in the file (headings, tables, the bracketed staging notes)
 * is for the person assembling the cut and must never reach the API.
 */
function parseScript() {
  const md = readFileSync(SCRIPT, 'utf8');
  const lines = [];
  const re = /^\*\*(\d{2})\*\*(.*)$/gm;
  let m;
  while ((m = re.exec(md))) {
    const id = m[1];
    const rest = md.slice(m.index + m[0].length);
    const stop = rest.search(/^\*\*\d{2}\*\*|^## /m);
    const body = stop === -1 ? rest : rest.slice(0, stop);
    const text = body
      .split('\n')
      .filter((l) => l.trim().startsWith('>'))
      .map((l) => l.replace(/^\s*>\s?/, '').trim())
      .join(' ')
      .replace(/\s+/g, ' ')
      .trim();
    if (text) lines.push({ id, text, note: m[2].replace(/`/g, '').trim() });
  }
  return lines;
}

// --- generate ----------------------------------------------------------------

async function listVoices(key) {
  const r = await fetch(`${API}/voices`, { headers: { 'xi-api-key': key } });
  if (!r.ok) throw new Error(`voices: ${r.status} ${await r.text()}`);
  const { voices } = await r.json();
  for (const v of voices) {
    const labels = Object.values(v.labels || {}).join(', ');
    console.log(`${v.voice_id}  ${(v.name || '').padEnd(18)} ${labels}`);
  }
}

/**
 * Speak one line.
 *
 * `prev` and `next` are the neighbouring lines' text, and `prevIds` the request
 * ids of what came before. Both are what stop seventeen separate requests
 * sounding like seventeen separate recordings: the model is told what it just
 * said and what it is about to say, so pitch and pace carry across the joins
 * instead of resetting at every paragraph.
 *
 * Returns the request id, to be fed forward into the next call.
 */
async function speak(key, voice, text, out, { prev, next, prevIds = [] } = {}) {
  const r = await fetch(`${API}/text-to-speech/${voice}?output_format=${FORMAT}`, {
    method: 'POST',
    headers: { 'xi-api-key': key, 'content-type': 'application/json', accept: 'audio/mpeg' },
    body: JSON.stringify({
      text,
      model_id: MODEL,
      voice_settings: SETTINGS,
      ...(prev ? { previous_text: prev } : {}),
      ...(next ? { next_text: next } : {}),
      // At most three, per the API.
      ...(prevIds.length ? { previous_request_ids: prevIds.slice(-3) } : {}),
    }),
  });
  if (!r.ok) throw new Error(`tts: ${r.status} ${await r.text()}`);
  writeFileSync(out, Buffer.from(await r.arrayBuffer()));
  return r.headers.get('request-id') || null;
}

// --- run ---------------------------------------------------------------------

const argv = process.argv.slice(2);
const has = (f) => argv.includes(f);
const valOf = (f) => { const i = argv.indexOf(f); return i === -1 ? null : argv[i + 1]; };

const key = apiKey();
if (has('--voices')) { await listVoices(key); process.exit(0); }

const voice = valOf('--voice') || DEFAULT_VOICE;
const only = valOf('--line');
const force = has('--force');

let lines = parseScript();
if (!lines.length) { console.error('No numbered lines found in docs/VOICEOVER.md'); process.exit(1); }
if (only) lines = lines.filter((l) => l.id === only.padStart(2, '0'));
if (!lines.length) { console.error('No such line: ' + only); process.exit(1); }

mkdirSync(OUT, { recursive: true });

// A hash of the words next to each file, so an unchanged line is neither
// re-generated nor re-billed, and a changed one is caught without being asked.
const stampFile = path.join(OUT, '.hashes.json');
const stamps = existsSync(stampFile) ? JSON.parse(readFileSync(stampFile, 'utf8')) : {};

let made = 0, kept = 0;
const ids = [];
for (let i = 0; i < lines.length; i++) {
  const l = lines[i];
  const out = path.join(OUT, `vo-${l.id}.mp3`);
  // The hash covers the neighbours too: changing line 9 changes how line 10 is
  // spoken, because 10 was generated knowing what 9 said.
  const prev = lines[i - 1] ? lines[i - 1].text : '';
  const next = lines[i + 1] ? lines[i + 1].text : '';
  const hash = createHash('sha1')
    .update([voice, MODEL, prev, l.text, next].join('\n')).digest('hex').slice(0, 12);

  if (!force && existsSync(out) && stamps[l.id]?.hash === hash) {
    kept += 1;
    if (stamps[l.id].id) ids.push(stamps[l.id].id);
    continue;
  }
  process.stdout.write(`${l.id}  ${l.text.slice(0, 62)}${l.text.length > 62 ? '...' : ''}`);
  const id = await speak(key, voice, l.text, out, { prev, next, prevIds: ids });
  if (id) ids.push(id);
  stamps[l.id] = { hash, id };
  made += 1;
  console.log('  -> vo-' + l.id + '.mp3');
}
writeFileSync(stampFile, JSON.stringify(stamps, null, 2));

const words = lines.reduce((n, l) => n + l.text.split(/\s+/).length, 0);
console.log(`\n${made} generated, ${kept} unchanged.`);
console.log(`${words} words total, roughly ${Math.round(words / 150 * 60)}s at a documentary pace.`);

// --- lay the lines onto the cut's timeline -----------------------------------

// One continuous track the length of the picture, with each line starting at the
// second it is meant to. Dropped into CapCut at 0:00 against
// media/tracer-silent.mp4, it is already in sync, so the edit is music and
// captions rather than nudging seventeen clips into place.
if (!has('--no-track') && !only) {
  const cues = JSON.parse(readFileSync(path.join(REPO, 'media/vo-cues.json'), 'utf8'));
  const dur = (f) => {
    const r = spawnSync(FFPROBE, ['-v', 'error', '-show_entries', 'format=duration',
      '-of', 'csv=p=0', f], { encoding: 'utf8' });
    return parseFloat(r.stdout.trim()) || 0;
  };

  const inputs = [];
  const filters = [];
  let n = 0;
  let overrun = false;
  for (const l of lines) {
    const f = path.join(OUT, `vo-${l.id}.mp3`);
    if (!existsSync(f)) continue;
    const cue = cues.lines[l.id];
    if (!cue) { console.log(`  no cue for line ${l.id}, skipped`); continue; }
    const ms = Math.round(cue.at * 1000);
    inputs.push('-i', f);
    filters.push(`[${n}:a]adelay=${ms}|${ms}[a${n}]`);
    const ends = cue.at + dur(f);
    if (ends > cue.until + 0.35) {
      console.log(`  line ${l.id} runs ${(ends - cue.until).toFixed(1)}s past its shot`);
      overrun = true;
    }
    n += 1;
  }

  if (n) {
    const track = path.join(REPO, 'media/tracer-voice.mp3');
    const graph = filters.join(';') +
      `;${filters.map((_, i) => `[a${i}]`).join('')}amix=inputs=${n}:normalize=0,` +
      `apad=whole_dur=${cues.total}[out]`;
    const r = spawnSync(FFMPEG, ['-y', ...inputs, '-filter_complex', graph,
      '-map', '[out]', '-c:a', 'libmp3lame', '-b:a', '192k', track], { encoding: 'utf8' });
    if (r.status !== 0) {
      console.log('\ntrack assembly failed:\n' + (r.stderr || '').split('\n').slice(-10).join('\n'));
    } else {
      console.log(`\n-> media/tracer-voice.mp3  (${cues.total}s, aligned to tracer-silent.mp4)`);
      if (overrun) console.log('   Some lines run past their shot. Trim the words, or hold the picture.');
    }
  }
}
